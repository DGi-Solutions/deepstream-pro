const assert = require('node:assert/strict');
const locale = require('../native/locale.js');
const {model, trackLabel} = require('../native/audioDetails.js');
assert.equal(locale.language({document:{documentElement:{lang:'de-DE'}},navigator:{language:'en-US'}}), 'de');
assert.equal(locale.language({document:{documentElement:{lang:'en-GB'}},navigator:{language:'de-DE'}}), 'en');
assert.equal(locale.language({document:{documentElement:{lang:''}},navigator:{language:'de-DE'}}), 'de');
assert.equal(locale.text('Zurück', 'en'), 'Back');
assert.equal(locale.text('Schließen', 'en'), 'Close');
assert.equal(locale.text('Wiedergabe', 'de'), 'Wiedergabe');
const stream = {Index:1, Type:'Audio', Codec:'truehd', Profile:'Dolby TrueHD + Dolby Atmos', Language:'deu', Channels:8, ChannelLayout:'7.1', SampleRate:48000, BitDepth:24, BitRate:5600000};
assert.equal(trackLabel(stream, 'en'), 'German · TrueHD / Atmos · 7.1 · 48 kHz · 24 Bit · 5.6 Mbit/s');
const value = model({source:{MediaStreams:[stream]},uiLanguage:'en'});
const rows = Object.fromEntries(value.rows);
assert.equal(rows.Language, 'German');
assert.equal(rows.Compression, 'Lossless');
assert.equal(rows.Bitrate, '5.6 Mbit/s');
assert.equal(value.selection, 'Automatic');
assert.equal(value.decoder, 'Not checked yet');
assert.equal(model({source:{MediaStreams:[stream]},uiLanguage:'de'}).rows[1][1], 'Deutsch');
console.log('Language: profile language, German/English labels, audio metadata and number formatting passed.');
